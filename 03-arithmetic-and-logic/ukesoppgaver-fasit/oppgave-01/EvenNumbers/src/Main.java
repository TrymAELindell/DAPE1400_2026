// Reference solution for exercise 1.
public class Main {
    public static void main(String[] args) {
        int count = 0;

        // We have not learned loops yet (they arrive in module 06), so we
        // repeat the same two statements by hand.
        count = count + 2;
        System.out.println(count);   // 2
        count = count + 2;
        System.out.println(count);   // 4
        count = count + 2;
        System.out.println(count);   // 6
        count = count + 2;
        System.out.println(count);   // 8
    }
}
