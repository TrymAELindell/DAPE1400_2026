// Reference solution for exercise 36.
public class Main {
    public static void main(String[] args) {
        // Six plain println lines are the right choice here. Nothing in the
        // menu changes while the program runs, so there is no value to
        // name, read in or calculate. Building one String with \n and
        // printing it once would also work. But it hides the line structure
        // in a single expression.
        System.out.println("Kaffekroken");
        System.out.println("Kaffe   35 kr");
        System.out.println("Te      30 kr");
        System.out.println("Vaffel  45 kr");
        System.out.println("Bolle   40 kr");
        System.out.println("Kakao   45 kr");
    }
}
